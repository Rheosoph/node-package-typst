use crate::{markdown::markdown_to_typst, shared::CATEGORY};
use flow_like_wasm_sdk::*;

#[register_node]
#[derive(Default)]
pub struct MarkdownToTypstNode;

impl WasmNode for MarkdownToTypstNode {
    fn get_node(&self) -> NodeDefinition {
        let mut node = NodeDefinition::new(
            "typst_markdown_to_typst",
            "Markdown to Typst",
            "Converts Flow-Like Markdown into a safe Typst body fragment, including static Nivo and Plotly charts",
            CATEGORY,
        );
        node.add_input_pin(
            "markdown",
            "Markdown",
            "Flow-Like Markdown generated by a model",
            VariableType::String,
        )
        .set_default_value(json!(""));
        node.add_output_pin(
            "typst_source",
            "Typst Source",
            "Typst body fragment ready for insertion into a document template",
            VariableType::String,
        );
        node.set_scores(NodeScores {
            privacy: 10,
            security: 10,
            performance: 8,
            governance: 9,
            reliability: 8,
            cost: 10,
        });
        node
    }

    fn run(&self, mut ctx: Context) -> ExecutionResult {
        let markdown = ctx.get_string("markdown").unwrap_or_default();
        let typst_source = match markdown_to_typst(&markdown) {
            Ok(source) => source,
            Err(error) => return ctx.fail(error),
        };
        ctx.set_output("typst_source", typst_source);
        ctx.finish()
    }
}
